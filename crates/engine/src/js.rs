//! The JavaScript engine.
//!
//! QuickJS through `rquickjs`, with a context built by `Context::custom` rather
//! than `Context::full`. That is not a style choice: `JS_NewContext` calls
//! `JS_AddPerformance`, which reads the clock during setup, and on this target
//! that call fails and aborts the process. The whole chain is in
//! [docs/quickjs.md](../../../docs/quickjs.md).
//!
//! Two consequences worth knowing:
//!
//!   * `performance` does not exist. In a browser it is a host facility, so the
//!     engine supplies it rather than QuickJS reading the wall clock.
//!   * `atob`/`btoa` do not exist, because `JS_AddIntrinsicAToB` is not
//!     reachable through `Context::custom`. Host functions fill the gap.
//!
//! Exceptions are captured through `CatchResultExt`, not read off `Error`.
//! Without that, every thrown exception reports as "Exception generated by
//! QuickJS" with no message, which makes a binding bug indistinguishable from a
//! page bug.

use std::sync::mpsc::{channel, Sender};
use std::sync::{Arc, Mutex};
use std::thread::JoinHandle;

use rquickjs::context::intrinsic;
use rquickjs::atom::PredefinedAtom;
use rquickjs::context::EvalOptions;
use rquickjs::{CatchResultExt, CaughtError, Context, Ctx, Runtime, Value};

/// Everything `JS_NewContext` installs, minus `JS_AddPerformance`.
type Intrinsics = (
    intrinsic::Eval,
    intrinsic::Json,
    intrinsic::Date,
    intrinsic::RegExp,
    intrinsic::RegExpCompiler,
    intrinsic::MapSet,
    intrinsic::Promise,
    intrinsic::TypedArrays,
    intrinsic::Proxy,
    intrinsic::WeakRef,
    intrinsic::DOMException,
);

/// A JavaScript value, flattened into what CDP can carry.
#[derive(Debug, Clone, PartialEq)]
pub enum JsValue {
    Undefined,
    Null,
    Bool(bool),
    Number(f64),
    String(String),
    /// An object, function or array. Handles are not tracked yet, so only the
    /// shape is reported.
    Object { class: String, is_function: bool },
}

impl JsValue {
    pub fn type_name(&self) -> &'static str {
        match self {
            JsValue::Undefined => "undefined",
            JsValue::Null => "object",
            JsValue::Bool(_) => "boolean",
            JsValue::Number(_) => "number",
            JsValue::String(_) => "string",
            JsValue::Object { is_function: true, .. } => "function",
            JsValue::Object { .. } => "object",
        }
    }
}

#[derive(Debug, Clone)]
pub struct JsError {
    pub message: String,
}

impl std::fmt::Display for JsError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.message)
    }
}

impl std::error::Error for JsError {}

/// Lines a page script wrote through `console`. Kept because a client can read
/// them back, and because they are the fastest way to debug a binding.
#[derive(Debug, Default, Clone)]
pub struct ConsoleLog {
    pub lines: Vec<String>,
}

pub struct JsRuntime {
    runtime: Runtime,
    context: Context,
    console: Arc<Mutex<ConsoleLog>>,
}

impl JsRuntime {
    pub fn new() -> Result<Self, JsError> {
        Self::with_console(Arc::new(Mutex::new(ConsoleLog::default())))
    }

    /// Shares the console sink, so the engine can read what page script wrote
    /// even though the runtime lives on another thread.
    pub fn with_console(console: Arc<Mutex<ConsoleLog>>) -> Result<Self, JsError> {
        let runtime = Runtime::new().map_err(map_error)?;
        let context = new_context(&runtime, &console)?;
        Ok(JsRuntime { runtime, context, console })
    }

    /// Replaces the context with a fresh one on the same runtime. A browser
    /// gives every document its own global object; without this, globals from
    /// the previous page linger, and a page that declares a top-level `const`
    /// fails the second time it loads.
    pub fn reset(&mut self) -> Result<(), JsError> {
        self.context = new_context(&self.runtime, &self.console)?;
        Ok(())
    }

    /// Evaluates and converts the result.
    ///
    /// Sloppy mode, not rquickjs's default of strict: a classic `<script>` and
    /// `Runtime.evaluate` both run sloppy in a browser, and page code that
    /// assigns an undeclared variable would otherwise throw.
    ///
    /// Promise reactions queued by the script run before this returns: a
    /// browser performs a microtask checkpoint after every script.
    pub fn evaluate(&self, source: &str) -> Result<JsValue, JsError> {
        let mut options = EvalOptions::default();
        options.strict = false;
        let result =
            self.context.with(|ctx| match ctx.eval_with_options::<Value, _>(source, options).catch(&ctx) {
                Ok(value) => Ok(to_js_value(&value)),
                Err(caught) => Err(caught_error(caught)),
            });
        self.run_microtasks();
        result
    }

    /// Runs queued Promise jobs until none are left. A job that throws is an
    /// unhandled rejection, which a browser reports and moves past; so does
    /// this. Bounded, because a job can queue another forever.
    pub fn run_microtasks(&self) {
        for _ in 0..1_000_000 {
            match self.runtime.execute_pending_job() {
                Ok(true) | Err(_) => continue,
                Ok(false) => break,
            }
        }
    }

    /// `Runtime.evaluate`: evaluates `source` as a global script and describes
    /// the result, or the exception, as CDP JSON. The description is built by
    /// the prelude (`prelude/90-cdp.js`), which also keeps the handles.
    pub fn cdp_evaluate(&self, source: &str, by_value: bool, await_promise: bool) -> String {
        let first = self.context.with(|ctx| {
            let describe: rquickjs::Function = match ctx.globals().get("__cdpResult") {
                Ok(f) => f,
                Err(_) => return cdp_error("the DOM prelude is not installed"),
            };
            let mut options = EvalOptions::default();
            options.strict = false;
            let (value, threw) = match ctx.eval_with_options::<Value, _>(source, options) {
                Ok(value) => (value, false),
                Err(rquickjs::Error::Exception) => (ctx.catch(), true),
                Err(e) => return cdp_error(&e.to_string()),
            };
            describe
                .call::<_, String>((value, threw, by_value, await_promise))
                .unwrap_or_else(|e| cdp_error(&e.to_string()))
        });
        self.run_microtasks();
        self.settle(first)
    }

    /// Evaluates a prelude call that answers in CDP JSON, such as
    /// `__cdpCall(...)`, and waits for a promise it parked.
    pub fn cdp_expression(&self, expression: &str) -> String {
        let first = match self.evaluate(expression) {
            Ok(JsValue::String(json)) => json,
            Ok(other) => cdp_error(&format!("the prelude answered {other:?}")),
            Err(e) => cdp_error(&e.message),
        };
        self.settle(first)
    }

    /// A promise the client asked to await is parked by the prelude under a
    /// token. The page runs until it settles, up to 30 virtual seconds at a
    /// time; when nothing is due within that, nothing will settle it, and
    /// that is reported rather than waited on.
    fn settle(&self, first: String) -> String {
        let token = serde_json::from_str::<serde_json::Value>(&first)
            .ok()
            .and_then(|v| v.get("pending").and_then(|t| t.as_u64()));
        let Some(token) = token else { return first };
        let check = format!("__cdpSettled({token})");
        for _ in 0..PROMISE_TURNS {
            if let Ok(JsValue::String(done)) = self.evaluate(&check) {
                if !done.is_empty() {
                    return done;
                }
            }
            if self.run_tasks(PROMISE_HORIZON_MS, 1_000) == 0 {
                break;
            }
        }
        match self.evaluate(&check) {
            Ok(JsValue::String(done)) if !done.is_empty() => done,
            _ => cdp_error("the promise did not settle: nothing the page has scheduled resolves it"),
        }
    }

    /// Runs the prelude's task queue: timers, animation frames and network
    /// completions, in due order on a virtual clock, with a microtask
    /// checkpoint after each. Stops when nothing is due within `budget_ms`
    /// of virtual time or after `max_tasks`, so a page polling on an interval
    /// cannot hold the engine. Returns how many tasks ran.
    pub fn run_tasks(&self, budget_ms: f64, max_tasks: usize) -> usize {
        if self.evaluate(&format!("__beginTurn({budget_ms})")).is_err() {
            return 0;
        }
        let mut ran = 0;
        while ran < max_tasks {
            match self.evaluate("__runNextTask()") {
                Ok(JsValue::Bool(true)) => ran += 1,
                _ => break,
            }
        }
        if std::env::var_os("WHB_TRACE_RESOURCES").is_some() {
            let usage = self.runtime.memory_usage();
            eprintln!("[resources] tasks: {ran}, QuickJS allocated {:.1} MiB, used {:.1} MiB", usage.malloc_size as f64 / 1048576.0, usage.memory_used_size as f64 / 1048576.0);
        }
        ran
    }

    /// Runs a snippet for its side effects, discarding the result. Used to load
    /// script text out of a document.
    pub fn run(&self, source: &str) -> Result<(), JsError> {
        self.evaluate(source).map(|_| ())
    }

    pub fn console_lines(&self) -> Vec<String> {
        self.console.lock().map(|log| log.lines.clone()).unwrap_or_default()
    }

    pub fn take_console_lines(&self) -> Vec<String> {
        self.console
            .lock()
            .map(|mut log| std::mem::take(&mut log.lines))
            .unwrap_or_default()
    }

    /// Enters the context, for installing globals and for tests.
    pub fn with<R>(&self, f: impl FnOnce(Ctx<'_>) -> R) -> R {
        self.context.with(f)
    }

    pub fn runtime(&self) -> &Runtime {
        &self.runtime
    }

    pub fn context(&self) -> &Context {
        &self.context
    }

    /// For tests only: evaluates and coerces to a string.
    #[cfg(test)]
    fn eval_to_string(&self, source: &str) -> Result<String, JsError> {
        match self.evaluate(source)? {
            JsValue::String(s) => Ok(s),
            JsValue::Number(n) => Ok(if n.fract() == 0.0 {
                format!("{}", n as i64)
            } else {
                format!("{n}")
            }),
            JsValue::Bool(b) => Ok(b.to_string()),
            JsValue::Null => Ok("null".to_string()),
            JsValue::Undefined => Ok("undefined".to_string()),
            JsValue::Object { class, .. } => Ok(class),
        }
    }
}

/// A context with every intrinsic except `Performance`, plus a host `console`
/// that writes to `console`.
fn new_context(runtime: &Runtime, console: &Arc<Mutex<ConsoleLog>>) -> Result<Context, JsError> {
    let context = Context::custom::<Intrinsics>(runtime).map_err(map_error)?;
    let log_sink = Arc::clone(console);
    context.with(|ctx| {
        let globals = ctx.globals();
        // A host-side `console` rather than QuickJS's own. It is small, it
        // is where a real browser puts it, and it gives tests something to
        // assert on.
        let console_object = rquickjs::Object::new(ctx.clone())
            .map_err(map_error)
            .expect("create console object");
        for method in ["log", "info", "warn", "error", "debug"] {
            let sink = Arc::clone(&log_sink);
            let prefix = if method == "log" || method == "info" { "" } else { method };
            let function = rquickjs::Function::new(
                ctx.clone(),
                move |args: rquickjs::function::Rest<Value>| {
                    let mut parts = Vec::new();
                    for value in args.iter() {
                        parts.push(stringify(value));
                    }
                    let mut line = parts.join(" ");
                    if !prefix.is_empty() {
                        line = format!("[{prefix}] {line}");
                    }
                    if let Ok(mut log) = sink.lock() {
                        log.lines.push(line);
                    }
                },
            )
            .map_err(map_error)
            .expect("create console method");
            let _ = console_object.set(method, function);
        }
        globals.set("console", console_object).map_err(map_error).expect("install console");
    });
    Ok(context)
}

/// How far ahead, in virtual time, an awaited promise's page looks for work,
/// and how many such turns it gets.
const PROMISE_HORIZON_MS: f64 = 30_000.0;
const PROMISE_TURNS: usize = 10;

/// A failure of the CDP plumbing itself, as opposed to a page exception.
fn cdp_error(message: &str) -> String {
    serde_json::json!({ "error": message }).to_string()
}

fn to_js_value(value: &Value<'_>) -> JsValue {
    if value.is_undefined() {
        return JsValue::Undefined;
    }
    if value.is_null() {
        return JsValue::Null;
    }
    if let Some(b) = value.as_bool() {
        return JsValue::Bool(b);
    }
    if let Some(i) = value.as_int() {
        return JsValue::Number(i as f64);
    }
    if let Some(f) = value.as_float() {
        return JsValue::Number(f);
    }
    if let Some(s) = value.as_string() {
        return JsValue::String(s.to_string().unwrap_or_default());
    }
    if value.is_function() {
        return JsValue::Object { class: "Function".to_string(), is_function: true };
    }
    // `Symbol.toStringTag` is where the DOM wrappers name their interface, and
    // what `Object.prototype.toString` reads. A plain object has none.
    let class = value
        .as_object()
        .and_then(|o| {
            o.get::<_, Option<String>>(PredefinedAtom::SymbolToStringTag).ok().flatten().or_else(|| {
                o.get::<_, Option<rquickjs::Object>>("constructor")
                    .ok()
                    .flatten()
                    .and_then(|c| c.get::<_, Option<String>>("name").ok().flatten())
            })
        })
        .filter(|name| !name.is_empty())
        .unwrap_or_else(|| "Object".to_string());
    JsValue::Object { class, is_function: false }
}

/// A best-effort string for one value, used by `console`.
fn stringify(value: &Value<'_>) -> String {
    if let Some(s) = value.as_string() {
        return s.to_string().unwrap_or_default();
    }
    match to_js_value(value) {
        JsValue::String(s) => s,
        JsValue::Number(n) => {
            if n.fract() == 0.0 {
                format!("{}", n as i64)
            } else {
                format!("{n}")
            }
        }
        JsValue::Bool(b) => b.to_string(),
        JsValue::Null => "null".into(),
        JsValue::Undefined => "undefined".into(),
        JsValue::Object { .. } => "[object]".into(),
    }
}

fn map_error(err: rquickjs::Error) -> JsError {
    JsError { message: err.to_string() }
}

/// Prefers the captured exception's own message over the generic placeholder.
fn caught_error(caught: CaughtError) -> JsError {
    let message = caught.to_string();
    if message.contains("Exception generated by QuickJS") {
        JsError {
            message: "JavaScript threw an exception, but its message could not be read".to_string(),
        }
    } else {
        JsError { message }
    }
}

#[cfg(test)]
mod tests {
    use super::{JsRuntime, JsValue};

    fn runtime() -> JsRuntime {
        JsRuntime::new().expect("runtime")
    }

    #[test]
    fn evaluates_real_javascript() {
        let js = runtime();
        assert_eq!(js.eval_to_string("String(1 + 1)").unwrap(), "2");
        assert_eq!(js.eval_to_string("['a','b'].join('-')").unwrap(), "a-b");
        assert_eq!(js.eval_to_string("[1,2,3].map(x => x*2).join(',')").unwrap(), "2,4,6");
        assert_eq!(
            js.eval_to_string("String((() => { let s = 0; for (let i=0;i<100;i++) s+=i; return s })())")
                .unwrap(),
            "4950"
        );
    }

    #[test]
    fn state_persists_between_evaluations() {
        // A page script is not one expression; globals have to survive.
        let js = runtime();
        js.run("globalThis.counter = 0").unwrap();
        js.run("globalThis.counter += 5").unwrap();
        assert_eq!(js.eval_to_string("String(globalThis.counter)").unwrap(), "5");
    }

    #[test]
    fn scripts_run_in_sloppy_mode_like_a_classic_script() {
        // Assigning an undeclared name is a ReferenceError in strict mode, and
        // plenty of page code does it.
        let js = runtime();
        js.run("undeclared = 3").unwrap();
        assert_eq!(js.eval_to_string("String(undeclared)").unwrap(), "3");
    }

    #[test]
    fn objects_report_their_constructor() {
        let js = runtime();
        assert_eq!(js.eval_to_string("[]").unwrap(), "Array");
        assert_eq!(js.eval_to_string("({})").unwrap(), "Object");
        assert_eq!(js.eval_to_string("new Map()").unwrap(), "Map");
    }

    #[test]
    fn function_caller_names_the_calling_function() {
        // vendor/patches/0001-function-caller.patch. Old class libraries find
        // the overridden method this way.
        let js = runtime();
        assert_eq!(
            js.eval_to_string(
                "function inner() { return inner.caller === outer; }\
                 function outer() { return inner(); }\
                 String(outer())"
            )
            .unwrap(),
            "true"
        );
        // Through apply, as `_super` implementations call it, the native frame
        // is skipped.
        assert_eq!(
            js.eval_to_string(
                "function callee() { return callee.caller === viaApply; }\
                 function viaApply() { return callee.apply(null, []); }\
                 String(viaApply())"
            )
            .unwrap(),
            "true"
        );
        // A strict caller is not revealed, and a function not running has none.
        assert_eq!(
            js.eval_to_string(
                "function probe() { return probe.caller; }\
                 const strict = function () { 'use strict'; return probe(); };\
                 String(strict()) + ' ' + String(probe.caller)"
            )
            .unwrap(),
            "null null"
        );
        // Strict functions still refuse, as the specification requires.
        assert!(js.evaluate("(function () { 'use strict'; }).caller").is_err());
    }

    #[test]
    fn thrown_exceptions_carry_their_message() {
        // This is the difference between a debuggable engine and a wall of
        // "Exception generated by QuickJS".
        let js = runtime();
        let err = js.evaluate("throw new Error('boom')").unwrap_err();
        assert!(err.message.contains("boom"), "message was: {}", err.message);

        let err = js.evaluate("undefinedThing.property").unwrap_err();
        assert!(
            err.message.contains("undefinedThing") || err.message.contains("undefined"),
            "message was: {}",
            err.message
        );

        let err = js.evaluate("JSON.parse('{')").unwrap_err();
        assert!(!err.message.contains("could not be read"), "message was: {}", err.message);
    }

    #[test]
    fn syntax_errors_are_reported() {
        let js = runtime();
        let err = js.evaluate("function {").unwrap_err();
        assert!(!err.message.is_empty());
    }

    #[test]
    fn values_are_classified_for_cdp() {
        let js = runtime();
        assert_eq!(js.evaluate("undefined").unwrap(), JsValue::Undefined);
        assert_eq!(js.evaluate("null").unwrap(), JsValue::Null);
        assert_eq!(js.evaluate("true").unwrap(), JsValue::Bool(true));
        assert_eq!(js.evaluate("42").unwrap(), JsValue::Number(42.0));
        assert_eq!(js.evaluate("'hi'").unwrap(), JsValue::String("hi".into()));
        assert_eq!(js.evaluate("({})").unwrap().type_name(), "object");
        assert_eq!(js.evaluate("(function(){})").unwrap().type_name(), "function");
        assert_eq!(js.evaluate("([])").unwrap().type_name(), "object");
    }

    #[test]
    fn numbers_keep_their_fraction() {
        let js = runtime();
        assert_eq!(js.evaluate("1.5").unwrap(), JsValue::Number(1.5));
        assert_eq!(js.evaluate("-0.25").unwrap(), JsValue::Number(-0.25));
    }

    #[test]
    fn console_calls_are_captured() {
        let js = runtime();
        js.run("console.log('hello', 'world')").unwrap();
        js.run("console.warn('careful')").unwrap();
        assert_eq!(js.console_lines(), vec!["hello world", "[warn] careful"]);
        // Taking clears.
        let taken = js.take_console_lines();
        assert_eq!(taken.len(), 2);
        assert!(js.console_lines().is_empty());
    }

    #[test]
    fn console_ids_are_absent_by_design() {
        // A regression guard for docs/quickjs.md: `Context::custom` cannot reach
        // `JS_AddIntrinsicAToB`, and `performance` lives in the intrinsic that
        // aborts. Both are supplied by the host instead.
        let js = runtime();
        assert_eq!(js.eval_to_string("String(typeof performance)").unwrap(), "undefined");
        assert_eq!(js.eval_to_string("String(typeof atob)").unwrap(), "undefined");
        // Date uses a different clock path and still works.
        assert_eq!(js.eval_to_string("String(Date.now() > 0)").unwrap(), "true");
    }

    #[test]
    fn libraries_that_a_page_expects_are_present() {
        let js = runtime();
        assert_eq!(js.eval_to_string("String(typeof Map)").unwrap(), "function");
        assert_eq!(js.eval_to_string("String(typeof Promise)").unwrap(), "function");
        assert_eq!(js.eval_to_string("String(typeof Proxy)").unwrap(), "function");
        assert_eq!(js.eval_to_string("String(typeof Uint8Array)").unwrap(), "function");
        assert_eq!(js.eval_to_string("String(typeof WeakRef)").unwrap(), "function");
    }
}

/// A JavaScript runtime confined to its own thread.
///
/// `rquickjs::Runtime` is only `Send` with rquickjs's `parallel` feature, which
/// pulls in a multi-threaded tokio runtime. Rather than take that dependency,
/// the runtime stays on one thread and the engine talks to it over a channel.
/// That keeps `Engine: Send`, which `browser-core` requires because it hands
/// engines to connection threads.
///
/// The DOM is *not* confined: it is an `Arc<Mutex<Document>>` shared with the
/// engine, so a mutation made by page script is visible to `Accessibility` and
/// the rest of the CDP surface immediately.
pub struct ScriptHost {
    requests: Sender<Request>,
    state: Arc<crate::bindings::DomState>,
    console: Arc<Mutex<ConsoleLog>>,
    thread: Option<JoinHandle<()>>,
}

/// The script thread's stack, and how much of it QuickJS may use.
///
/// React renders by recursion, and a QuickJS call costs far more native stack
/// than a V8 one, so QuickJS's default limit of 1 MB overflows on an ordinary
/// login page. The rest of the stack is headroom for Rust and native
/// functions, so a runaway script gets a RangeError rather than a crash.
const SCRIPT_THREAD_STACK: usize = 32 * 1024 * 1024;
const SCRIPT_STACK_LIMIT: usize = 24 * 1024 * 1024;

enum Request {
    Evaluate { source: String, reply: Sender<Result<JsValue, JsError>> },
    /// A fresh context with the bindings reinstalled, for a new document.
    Reset { reply: Sender<Result<(), JsError>> },
    RunTasks { budget_ms: f64, max_tasks: usize, reply: Sender<usize> },
    CdpEvaluate { source: String, by_value: bool, await_promise: bool, reply: Sender<String> },
    CdpExpression { expression: String, reply: Sender<String> },
    Shutdown,
}

impl ScriptHost {
    /// Starts the script thread, installs the bindings, and returns once the
    /// runtime is ready to evaluate. A failure to start is reported here rather
    /// than on the first evaluation.
    pub fn spawn(
        doc: Arc<Mutex<crate::dom::Document>>,
        client: crate::fetch::Client,
        viewport: (f64, f64),
        user_agent: &str,
    ) -> Result<Self, JsError> {
        let (requests, inbox) = channel::<Request>();
        let console = Arc::new(Mutex::new(ConsoleLog::default()));
        let state = Arc::new(crate::bindings::DomState::new(doc, client, viewport, user_agent));
        let (ready_tx, ready_rx) = channel::<Result<(), JsError>>();

        let thread_state = Arc::clone(&state);
        let thread_console = Arc::clone(&console);
        let thread = std::thread::Builder::new()
            .name("script".to_string())
            .stack_size(SCRIPT_THREAD_STACK)
            .spawn(move || {
                let mut js = match JsRuntime::with_console(thread_console) {
                    Ok(js) => js,
                    Err(e) => {
                        let _ = ready_tx.send(Err(e));
                        return;
                    }
                };
                // Only here, where the thread's stack is known to be larger.
                js.runtime().set_max_stack_size(SCRIPT_STACK_LIMIT);
                // A promise rejected with no handler is the page's to report,
                // once the current task is done with it (prelude/90-cdp.js).
                js.runtime().set_host_promise_rejection_tracker(Some(Box::new(|ctx, promise, reason, handled| {
                    if let Ok(track) = ctx.globals().get::<_, rquickjs::Function>("__promiseRejection") {
                        if track.call::<_, ()>((promise, reason, handled)).is_err() {
                            let _ = ctx.catch();
                        }
                    }
                })));
                // Modules resolve and load through the page; see modules.rs.
                js.runtime().set_loader(
                    crate::modules::PageResolver(Arc::clone(&thread_state)),
                    crate::modules::PageLoader(Arc::clone(&thread_state)),
                );
                if let Err(e) = js.with(|ctx| crate::bindings::install(&ctx, &thread_state)) {
                    let _ = ready_tx.send(Err(e));
                    return;
                }
                let _ = ready_tx.send(Ok(()));

                while let Ok(request) = inbox.recv() {
                    match request {
                        Request::Evaluate { source, reply } => {
                            let _ = reply.send(js.evaluate(&source));
                        }
                        Request::RunTasks { budget_ms, max_tasks, reply } => {
                            let _ = reply.send(js.run_tasks(budget_ms, max_tasks));
                        }
                        Request::CdpEvaluate { source, by_value, await_promise, reply } => {
                            let _ = reply.send(js.cdp_evaluate(&source, by_value, await_promise));
                        }
                        Request::CdpExpression { expression, reply } => {
                            let _ = reply.send(js.cdp_expression(&expression));
                        }
                        Request::Reset { reply } => {
                            thread_state.reset_page();
                            let result = js
                                .reset()
                                .and_then(|()| js.with(|ctx| crate::bindings::install(&ctx, &thread_state)));
                            let _ = reply.send(result);
                        }
                        Request::Shutdown => break,
                    }
                }
            })
            .map_err(|e| JsError { message: format!("could not start the script thread: {e}") })?;

        match ready_rx.recv() {
            Ok(Ok(())) => Ok(ScriptHost { requests, state, console, thread: Some(thread) }),
            Ok(Err(e)) => {
                let _ = thread.join();
                Err(e)
            }
            Err(_) => Err(JsError {
                message: "the script thread stopped before it was ready".to_string(),
            }),
        }
    }

    pub fn evaluate(&self, source: &str) -> Result<JsValue, JsError> {
        let (reply_tx, reply_rx) = channel();
        self.requests
            .send(Request::Evaluate { source: source.to_string(), reply: reply_tx })
            .map_err(|_| JsError { message: "the script thread is gone".to_string() })?;
        reply_rx.recv().map_err(|_| JsError {
            message: "the script thread stopped while evaluating".to_string(),
        })?
    }

    /// Runs a snippet for its side effects.
    pub fn run(&self, source: &str) -> Result<(), JsError> {
        self.evaluate(source).map(|_| ())
    }

    /// Starts a new global environment for a new document. The document
    /// lock must not be held: installing the bindings reads the document.
    pub fn reset(&self) -> Result<(), JsError> {
        let (reply_tx, reply_rx) = channel();
        self.requests
            .send(Request::Reset { reply: reply_tx })
            .map_err(|_| JsError { message: "the script thread is gone".to_string() })?;
        reply_rx.recv().map_err(|_| JsError {
            message: "the script thread stopped while resetting".to_string(),
        })?
    }

    /// See [`JsRuntime::cdp_evaluate`].
    pub fn cdp_evaluate(&self, source: &str, by_value: bool, await_promise: bool) -> serde_json::Value {
        let (reply, answer) = channel();
        let request = Request::CdpEvaluate { source: source.to_string(), by_value, await_promise, reply };
        self.cdp_round_trip(request, answer)
    }

    /// The console messages and exceptions the page queued since the last
    /// call, as `(method, params)` for `Runtime.*` events.
    pub fn take_page_events(&self) -> Vec<(String, serde_json::Value)> {
        let taken = self.cdp_expression("__cdpTakeEvents()");
        serde_json::from_value::<Vec<(String, serde_json::Value)>>(taken).unwrap_or_default()
    }

    /// See [`JsRuntime::cdp_expression`].
    pub fn cdp_expression(&self, expression: &str) -> serde_json::Value {
        let (reply, answer) = channel();
        self.cdp_round_trip(Request::CdpExpression { expression: expression.to_string(), reply }, answer)
    }

    fn cdp_round_trip(&self, request: Request, answer: std::sync::mpsc::Receiver<String>) -> serde_json::Value {
        let text = if self.requests.send(request).is_ok() {
            answer.recv().unwrap_or_else(|_| cdp_error("the script thread stopped while evaluating"))
        } else {
            cdp_error("the script thread is gone")
        };
        serde_json::from_str(&text).unwrap_or_else(|e| serde_json::json!({ "error": format!("unreadable answer: {e}") }))
    }

    /// See [`JsRuntime::run_tasks`]. Returns how many tasks ran.
    pub fn run_tasks(&self, budget_ms: f64, max_tasks: usize) -> usize {
        let (reply_tx, reply_rx) = channel();
        if self.requests.send(Request::RunTasks { budget_ms, max_tasks, reply: reply_tx }).is_err() {
            return 0;
        }
        reply_rx.recv().unwrap_or(0)
    }

    pub fn state(&self) -> &Arc<crate::bindings::DomState> {
        &self.state
    }

    pub fn console_lines(&self) -> Vec<String> {
        self.console.lock().map(|log| log.lines.clone()).unwrap_or_default()
    }

    pub fn take_console_lines(&self) -> Vec<String> {
        self.console
            .lock()
            .map(|mut log| std::mem::take(&mut log.lines))
            .unwrap_or_default()
    }
}

impl Drop for ScriptHost {
    fn drop(&mut self) {
        let _ = self.requests.send(Request::Shutdown);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}
