//! The JavaScript engine.
//!
//! QuickJS through `rquickjs`, with a context built by `Context::custom` rather
//! than `Context::full`. That is not a style choice: `JS_NewContext` calls
//! `JS_AddPerformance`, which reads the clock during setup, and on this target
//! that call fails and aborts the process. The whole chain is in
//! [docs/quickjs.md](../../../docs/quickjs.md).
//!
//! Two consequences worth knowing:
//!
//!   * `performance` does not exist. In a browser it is a host facility, so the
//!     engine supplies it rather than QuickJS reading the wall clock.
//!   * `atob`/`btoa` do not exist, because `JS_AddIntrinsicAToB` is not
//!     reachable through `Context::custom`. Host functions fill the gap.
//!
//! Exceptions are captured through `CatchResultExt`, not read off `Error`.
//! Without that, every thrown exception reports as "Exception generated by
//! QuickJS" with no message, which makes a binding bug indistinguishable from a
//! page bug.

use std::sync::mpsc::{channel, Sender};
use std::sync::{Arc, Mutex};
use std::thread::JoinHandle;

use rquickjs::context::intrinsic;
use rquickjs::{CatchResultExt, CaughtError, Context, Ctx, Runtime, Value};

/// Everything `JS_NewContext` installs, minus `JS_AddPerformance`.
type Intrinsics = (
    intrinsic::Eval,
    intrinsic::Json,
    intrinsic::Date,
    intrinsic::RegExp,
    intrinsic::RegExpCompiler,
    intrinsic::MapSet,
    intrinsic::Promise,
    intrinsic::TypedArrays,
    intrinsic::Proxy,
    intrinsic::WeakRef,
    intrinsic::DOMException,
);

/// A JavaScript value, flattened into what CDP can carry.
#[derive(Debug, Clone, PartialEq)]
pub enum JsValue {
    Undefined,
    Null,
    Bool(bool),
    Number(f64),
    String(String),
    /// An object, function or array. Handles are not tracked yet, so only the
    /// shape is reported.
    Object { class: String, is_function: bool },
}

impl JsValue {
    pub fn type_name(&self) -> &'static str {
        match self {
            JsValue::Undefined => "undefined",
            JsValue::Null => "object",
            JsValue::Bool(_) => "boolean",
            JsValue::Number(_) => "number",
            JsValue::String(_) => "string",
            JsValue::Object { is_function: true, .. } => "function",
            JsValue::Object { .. } => "object",
        }
    }
}

#[derive(Debug, Clone)]
pub struct JsError {
    pub message: String,
}

impl std::fmt::Display for JsError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.message)
    }
}

impl std::error::Error for JsError {}

/// Lines a page script wrote through `console`. Kept because a client can read
/// them back, and because they are the fastest way to debug a binding.
#[derive(Debug, Default, Clone)]
pub struct ConsoleLog {
    pub lines: Vec<String>,
}

pub struct JsRuntime {
    runtime: Runtime,
    context: Context,
    console: Arc<Mutex<ConsoleLog>>,
}

impl JsRuntime {
    pub fn new() -> Result<Self, JsError> {
        Self::with_console(Arc::new(Mutex::new(ConsoleLog::default())))
    }

    /// Shares the console sink, so the engine can read what page script wrote
    /// even though the runtime lives on another thread.
    pub fn with_console(console: Arc<Mutex<ConsoleLog>>) -> Result<Self, JsError> {
        let runtime = Runtime::new().map_err(map_error)?;
        let context = Context::custom::<Intrinsics>(&runtime).map_err(map_error)?;

        let log_sink = Arc::clone(&console);
        context.with(|ctx| {
            let globals = ctx.globals();
            // A host-side `console` rather than QuickJS's own. It is small, it
            // is where a real browser puts it, and it gives tests something to
            // assert on.
            let console_object = rquickjs::Object::new(ctx.clone())
                .map_err(map_error)
                .expect("create console object");
            for method in ["log", "info", "warn", "error", "debug"] {
                let sink = Arc::clone(&log_sink);
                let prefix = if method == "log" || method == "info" { "" } else { method };
                let function = rquickjs::Function::new(
                    ctx.clone(),
                    move |args: rquickjs::function::Rest<Value>| {
                        let mut parts = Vec::new();
                        for value in args.iter() {
                            parts.push(stringify(value));
                        }
                        let mut line = parts.join(" ");
                        if !prefix.is_empty() {
                            line = format!("[{prefix}] {line}");
                        }
                        if let Ok(mut log) = sink.lock() {
                            log.lines.push(line);
                        }
                    },
                )
                .map_err(map_error)
                .expect("create console method");
                let _ = console_object.set(method, function);
            }
            globals.set("console", console_object).map_err(map_error).expect("install console");
        });

        Ok(JsRuntime { runtime, context, console })
    }

    /// Evaluates and converts the result.
    pub fn evaluate(&self, source: &str) -> Result<JsValue, JsError> {
        self.context.with(|ctx| match ctx.eval::<Value, _>(source).catch(&ctx) {
            Ok(value) => Ok(to_js_value(&value)),
            Err(caught) => Err(caught_error(caught)),
        })
    }

    /// Runs a snippet for its side effects, discarding the result. Used to load
    /// script text out of a document.
    pub fn run(&self, source: &str) -> Result<(), JsError> {
        self.evaluate(source).map(|_| ())
    }

    pub fn console_lines(&self) -> Vec<String> {
        self.console.lock().map(|log| log.lines.clone()).unwrap_or_default()
    }

    pub fn take_console_lines(&self) -> Vec<String> {
        self.console
            .lock()
            .map(|mut log| std::mem::take(&mut log.lines))
            .unwrap_or_default()
    }

    /// Enters the context, for installing globals and for tests.
    pub fn with<R>(&self, f: impl FnOnce(Ctx<'_>) -> R) -> R {
        self.context.with(f)
    }

    pub fn runtime(&self) -> &Runtime {
        &self.runtime
    }

    pub fn context(&self) -> &Context {
        &self.context
    }

    /// For tests only: evaluates and coerces to a string.
    #[cfg(test)]
    fn eval_to_string(&self, source: &str) -> Result<String, JsError> {
        match self.evaluate(source)? {
            JsValue::String(s) => Ok(s),
            JsValue::Number(n) => Ok(if n.fract() == 0.0 {
                format!("{}", n as i64)
            } else {
                format!("{n}")
            }),
            JsValue::Bool(b) => Ok(b.to_string()),
            JsValue::Null => Ok("null".to_string()),
            JsValue::Undefined => Ok("undefined".to_string()),
            JsValue::Object { class, .. } => Ok(class),
        }
    }
}

fn to_js_value(value: &Value<'_>) -> JsValue {
    if value.is_undefined() {
        return JsValue::Undefined;
    }
    if value.is_null() {
        return JsValue::Null;
    }
    if let Some(b) = value.as_bool() {
        return JsValue::Bool(b);
    }
    if let Some(i) = value.as_int() {
        return JsValue::Number(i as f64);
    }
    if let Some(f) = value.as_float() {
        return JsValue::Number(f);
    }
    if let Some(s) = value.as_string() {
        return JsValue::String(s.to_string().unwrap_or_default());
    }
    if value.is_function() {
        return JsValue::Object { class: "Function".to_string(), is_function: true };
    }
    let class = value
        .as_object()
        .and_then(|o| o.get::<_, Option<String>>("constructor").ok().flatten())
        .unwrap_or_else(|| "Object".to_string());
    JsValue::Object { class, is_function: false }
}

/// A best-effort string for one value, used by `console`.
fn stringify(value: &Value<'_>) -> String {
    if let Some(s) = value.as_string() {
        return s.to_string().unwrap_or_default();
    }
    match to_js_value(value) {
        JsValue::String(s) => s,
        JsValue::Number(n) => {
            if n.fract() == 0.0 {
                format!("{}", n as i64)
            } else {
                format!("{n}")
            }
        }
        JsValue::Bool(b) => b.to_string(),
        JsValue::Null => "null".into(),
        JsValue::Undefined => "undefined".into(),
        JsValue::Object { .. } => "[object]".into(),
    }
}

fn map_error(err: rquickjs::Error) -> JsError {
    JsError { message: err.to_string() }
}

/// Prefers the captured exception's own message over the generic placeholder.
fn caught_error(caught: CaughtError) -> JsError {
    let message = caught.to_string();
    if message.contains("Exception generated by QuickJS") {
        JsError {
            message: "JavaScript threw an exception, but its message could not be read".to_string(),
        }
    } else {
        JsError { message }
    }
}

#[cfg(test)]
mod tests {
    use super::{JsRuntime, JsValue};

    fn runtime() -> JsRuntime {
        JsRuntime::new().expect("runtime")
    }

    #[test]
    fn evaluates_real_javascript() {
        let js = runtime();
        assert_eq!(js.eval_to_string("String(1 + 1)").unwrap(), "2");
        assert_eq!(js.eval_to_string("['a','b'].join('-')").unwrap(), "a-b");
        assert_eq!(js.eval_to_string("[1,2,3].map(x => x*2).join(',')").unwrap(), "2,4,6");
        assert_eq!(
            js.eval_to_string("String((() => { let s = 0; for (let i=0;i<100;i++) s+=i; return s })())")
                .unwrap(),
            "4950"
        );
    }

    #[test]
    fn state_persists_between_evaluations() {
        // A page script is not one expression; globals have to survive.
        let js = runtime();
        js.run("globalThis.counter = 0").unwrap();
        js.run("globalThis.counter += 5").unwrap();
        assert_eq!(js.eval_to_string("String(globalThis.counter)").unwrap(), "5");
    }

    #[test]
    fn thrown_exceptions_carry_their_message() {
        // This is the difference between a debuggable engine and a wall of
        // "Exception generated by QuickJS".
        let js = runtime();
        let err = js.evaluate("throw new Error('boom')").unwrap_err();
        assert!(err.message.contains("boom"), "message was: {}", err.message);

        let err = js.evaluate("undefinedThing.property").unwrap_err();
        assert!(
            err.message.contains("undefinedThing") || err.message.contains("undefined"),
            "message was: {}",
            err.message
        );

        let err = js.evaluate("JSON.parse('{')").unwrap_err();
        assert!(!err.message.contains("could not be read"), "message was: {}", err.message);
    }

    #[test]
    fn syntax_errors_are_reported() {
        let js = runtime();
        let err = js.evaluate("function {").unwrap_err();
        assert!(!err.message.is_empty());
    }

    #[test]
    fn values_are_classified_for_cdp() {
        let js = runtime();
        assert_eq!(js.evaluate("undefined").unwrap(), JsValue::Undefined);
        assert_eq!(js.evaluate("null").unwrap(), JsValue::Null);
        assert_eq!(js.evaluate("true").unwrap(), JsValue::Bool(true));
        assert_eq!(js.evaluate("42").unwrap(), JsValue::Number(42.0));
        assert_eq!(js.evaluate("'hi'").unwrap(), JsValue::String("hi".into()));
        assert_eq!(js.evaluate("({})").unwrap().type_name(), "object");
        assert_eq!(js.evaluate("(function(){})").unwrap().type_name(), "function");
        assert_eq!(js.evaluate("([])").unwrap().type_name(), "object");
    }

    #[test]
    fn numbers_keep_their_fraction() {
        let js = runtime();
        assert_eq!(js.evaluate("1.5").unwrap(), JsValue::Number(1.5));
        assert_eq!(js.evaluate("-0.25").unwrap(), JsValue::Number(-0.25));
    }

    #[test]
    fn console_calls_are_captured() {
        let js = runtime();
        js.run("console.log('hello', 'world')").unwrap();
        js.run("console.warn('careful')").unwrap();
        assert_eq!(js.console_lines(), vec!["hello world", "[warn] careful"]);
        // Taking clears.
        let taken = js.take_console_lines();
        assert_eq!(taken.len(), 2);
        assert!(js.console_lines().is_empty());
    }

    #[test]
    fn console_ids_are_absent_by_design() {
        // A regression guard for docs/quickjs.md: `Context::custom` cannot reach
        // `JS_AddIntrinsicAToB`, and `performance` lives in the intrinsic that
        // aborts. Both are supplied by the host instead.
        let js = runtime();
        assert_eq!(js.eval_to_string("String(typeof performance)").unwrap(), "undefined");
        assert_eq!(js.eval_to_string("String(typeof atob)").unwrap(), "undefined");
        // Date uses a different clock path and still works.
        assert_eq!(js.eval_to_string("String(Date.now() > 0)").unwrap(), "true");
    }

    #[test]
    fn libraries_that_a_page_expects_are_present() {
        let js = runtime();
        assert_eq!(js.eval_to_string("String(typeof Map)").unwrap(), "function");
        assert_eq!(js.eval_to_string("String(typeof Promise)").unwrap(), "function");
        assert_eq!(js.eval_to_string("String(typeof Proxy)").unwrap(), "function");
        assert_eq!(js.eval_to_string("String(typeof Uint8Array)").unwrap(), "function");
        assert_eq!(js.eval_to_string("String(typeof WeakRef)").unwrap(), "function");
    }
}

/// A JavaScript runtime confined to its own thread.
///
/// `rquickjs::Runtime` is only `Send` with rquickjs's `parallel` feature, which
/// pulls in a multi-threaded tokio runtime. Rather than take that dependency,
/// the runtime stays on one thread and the engine talks to it over a channel.
/// That keeps `Engine: Send`, which `browser-core` requires because it hands
/// engines to connection threads.
///
/// The DOM is *not* confined: it is an `Arc<Mutex<Document>>` shared with the
/// engine, so a mutation made by page script is visible to `Accessibility` and
/// the rest of the CDP surface immediately.
pub struct ScriptHost {
    requests: Sender<Request>,
    state: Arc<crate::bindings::DomState>,
    console: Arc<Mutex<ConsoleLog>>,
    thread: Option<JoinHandle<()>>,
}

enum Request {
    Evaluate { source: String, reply: Sender<Result<JsValue, JsError>> },
    Shutdown,
}

impl ScriptHost {
    /// Starts the script thread, installs the bindings, and returns once the
    /// runtime is ready to evaluate. A failure to start is reported here rather
    /// than on the first evaluation.
    pub fn spawn(
        doc: Arc<Mutex<crate::dom::Document>>,
        viewport: (f64, f64),
        user_agent: &str,
    ) -> Result<Self, JsError> {
        let (requests, inbox) = channel::<Request>();
        let console = Arc::new(Mutex::new(ConsoleLog::default()));
        let state = Arc::new(crate::bindings::DomState::new(doc, viewport, user_agent));
        let (ready_tx, ready_rx) = channel::<Result<(), JsError>>();

        let thread_state = Arc::clone(&state);
        let thread_console = Arc::clone(&console);
        let thread = std::thread::Builder::new()
            .name("script".to_string())
            .spawn(move || {
                let js = match JsRuntime::with_console(thread_console) {
                    Ok(js) => js,
                    Err(e) => {
                        let _ = ready_tx.send(Err(e));
                        return;
                    }
                };
                if let Err(e) = js.with(|ctx| crate::bindings::install(&ctx, &thread_state)) {
                    let _ = ready_tx.send(Err(e));
                    return;
                }
                let _ = ready_tx.send(Ok(()));

                while let Ok(request) = inbox.recv() {
                    match request {
                        Request::Evaluate { source, reply } => {
                            let _ = reply.send(js.evaluate(&source));
                        }
                        Request::Shutdown => break,
                    }
                }
            })
            .map_err(|e| JsError { message: format!("could not start the script thread: {e}") })?;

        match ready_rx.recv() {
            Ok(Ok(())) => Ok(ScriptHost { requests, state, console, thread: Some(thread) }),
            Ok(Err(e)) => {
                let _ = thread.join();
                Err(e)
            }
            Err(_) => Err(JsError {
                message: "the script thread stopped before it was ready".to_string(),
            }),
        }
    }

    pub fn evaluate(&self, source: &str) -> Result<JsValue, JsError> {
        let (reply_tx, reply_rx) = channel();
        self.requests
            .send(Request::Evaluate { source: source.to_string(), reply: reply_tx })
            .map_err(|_| JsError { message: "the script thread is gone".to_string() })?;
        reply_rx.recv().map_err(|_| JsError {
            message: "the script thread stopped while evaluating".to_string(),
        })?
    }

    /// Runs a snippet for its side effects.
    pub fn run(&self, source: &str) -> Result<(), JsError> {
        self.evaluate(source).map(|_| ())
    }

    pub fn state(&self) -> &Arc<crate::bindings::DomState> {
        &self.state
    }

    pub fn console_lines(&self) -> Vec<String> {
        self.console.lock().map(|log| log.lines.clone()).unwrap_or_default()
    }

    pub fn take_console_lines(&self) -> Vec<String> {
        self.console
            .lock()
            .map(|mut log| std::mem::take(&mut log.lines))
            .unwrap_or_default()
    }
}

impl Drop for ScriptHost {
    fn drop(&mut self) {
        let _ = self.requests.send(Request::Shutdown);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}
